"""Generate the static product pages and homepage search from the category HTML."""

import argparse
import json
import re
from html import escape, unescape
from html.parser import HTMLParser
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PRODUCTS = ROOT / "products"
GENERATED = "<!-- Generated by tools/build_product_pages.py. Edit the category page instead. -->"
GRID = re.compile(r'(<section class="products-grid">)(.*?)(</section>)', re.S)
HEADING = re.compile(r'<h3>(.*?)</h3>', re.S)
IMAGE_LINK = re.compile(r'<a class="product-image-link" [^>]*></a>')
GALLERY = re.compile(r'(<div class="product-image[^"]*">)(.*?)(</div>)', re.S)
PRICE = re.compile(r'<div class="price">(.*?)</div>', re.S)
DESCRIPTION = re.compile(r'<div class="desc-panel">\s*<p>(.*?)</p>', re.S)
PRODUCT_INFO = re.compile(r'<div class="desc-panel">(.*?)</div>', re.S)
FLAVORS = re.compile(r'<select class="flavor-select">.*?</select>', re.S)
LOCAL_LINK = re.compile(r'(\b(?:href|src)=")(?![a-z][a-z\d+.-]*:|/|#)([^"]+)(")', re.I)
IMAGE = re.compile(r'<img\b[^>]*\bsrc="([^"]+)"[^>]*>')
IMAGE_TYPES = {".avif", ".gif", ".jpeg", ".jfif", ".jpg", ".png", ".svg", ".webp"}


def plain_text(markup):
    return " ".join(unescape(re.sub(r"<[^>]+>", "", markup)).split())


class CardParser(HTMLParser):
    """Locate cards without rewriting the surrounding hand-authored category HTML."""

    def __init__(self, markup):
        super().__init__()
        self.lines = [0]
        for match in re.finditer("\n", markup):
            self.lines.append(match.end())
        self.cards = []
        self.card_count = 0
        self.divs = []
        self.feed(markup)
        if len(self.cards) != self.card_count:
            raise ValueError("Every product card needs a closing div")

    def source_offset(self):
        line, column = self.getpos()
        return self.lines[line - 1] + column

    def handle_starttag(self, tag, attrs):
        if tag == "div":
            attributes = dict(attrs)
            if "product-card" in attributes.get("class", "").split():
                self.card_count += 1
            self.divs.append((self.source_offset(), attributes))

    def handle_endtag(self, tag):
        if tag != "div" or not self.divs:
            return
        start, attrs = self.divs.pop()
        if "product-card" in attrs.get("class", "").split():
            self.cards.append((start, self.source_offset() + len("</div>"), attrs))


def detail_gallery(match, name):
    images = []
    for match_image in IMAGE.finditer(match[2]):
        src = unescape(match_image[1])
        path = ROOT / src
        if path.suffix.lower() in IMAGE_TYPES and path.is_file():
            images.append(escape(src))
    if not images:
        return ""

    thumbs = ""
    if len(images) > 1:
        buttons = []
        for index, src in enumerate(images):
            active = "true" if index == 0 else "false"
            buttons.append(
                f'<button type="button" aria-pressed="{active}" '
                f'aria-label="View photo {index + 1}"><img src="{src}" alt=""></button>'
            )
        thumbs = f'<div class="detail-thumbnails" role="group" aria-label="Product photos">{"".join(buttons)}</div>'

    return f'''<div class="detail-gallery">
        <button class="detail-photo" type="button" aria-label="Enlarge product photo">
            <img src="{images[0]}" alt="{escape(name)}" width="480" height="480">
            <span class="detail-zoom" aria-hidden="true">
                <svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.7">
                    <circle cx="10.5" cy="10.5" r="5.5"/><path d="m15 15 4 4M8 10.5h5m-2.5-2.5v5"/>
                </svg>
            </span>
        </button>
        {thumbs}
    </div>'''


def product_purchase(card, in_stock):
    if not in_stock:
        return '<p class="detail-stock-note">This product is currently unavailable to order.</p>'

    flavor = FLAVORS.search(card)
    options = ""
    if flavor:
        select = re.sub(r"<option>\s*</option>", "", flavor[0])
        select = select.replace('class="flavor-select"', 'class="flavor-select" id="product-flavor"')
        options = f'''<div class="detail-options">
            <label for="product-flavor">Flavor</label>
            {select}
        </div>'''
    return f'''{options}
        <div class="product-actions">
            <button class="cart-btn" type="button" onclick="addDetailProductToCart(this)">Add to Cart</button>
            <button class="order-btn" type="button" onclick="openOrderModal(this)">Order via WhatsApp</button>
        </div>
        <p class="detail-cart-status" role="status"></p>'''


def product_page(source, category_path, category, name, card, in_stock):
    description = DESCRIPTION.search(card)
    summary = plain_text(description[1]) if description else (
        f"View {name} in {category} at Dr Supplements."
    )
    gallery_match = GALLERY.search(card)
    if gallery_match is None:
        raise ValueError(f"Missing image container for {name}")
    gallery = detail_gallery(gallery_match, name)
    price = plain_text(PRICE.search(card)[1]).replace("$", "").strip()
    pricing = (
        f'<p class="price">${escape(price)}</p><span class="detail-stock">Available to order</span>'
        if in_stock else '<span class="detail-stock is-unavailable">Out of stock</span>'
    )
    info = ""
    info_match = PRODUCT_INFO.search(card)
    if info_match and plain_text(info_match[1]):
        info = f'''<section class="detail-info" aria-labelledby="detail-info-heading">
                <h2 id="detail-info-heading">Product details</h2>
                {info_match[1].strip()}
            </section>'''

    body = f'''<main class="product-detail">
    <nav class="detail-breadcrumb" aria-label="Breadcrumb">
        <a href="index.html">Home</a>
        <span aria-hidden="true">/</span>
        <a href="{category_path.name}">{escape(category)}</a>
    </nav>
    <article class="product-card product-detail-card{' has-gallery' if gallery else ''}">
        {gallery}
        <div class="product-detail-content">
            <h1>{escape(name)}</h1>
            <div class="detail-pricing">{pricing}</div>
            {product_purchase(card, in_stock)}
            {info}
        </div>
    </article>
</main>'''
    grid = GRID.search(source)
    section = re.search(r'<section class="section-title">.*?</section>', source, re.S)
    page = source[:section.start()] + body + source[grid.end():]
    page = re.sub(
        r"<title>.*?</title>",
        lambda _: f'<title>{escape(name)} | Dr Supplements</title>\n'
        f'<meta name="description" content="{escape(summary)}">',
        page,
        count=1,
    )
    page = page.replace('card.querySelector("h3")', 'card.querySelector("h1")')
    page = page.replace("</head>", '<link rel="stylesheet" href="product-detail.css">\n'
                        '<script src="product-detail.js" defer></script>\n</head>', 1)
    page = page.replace("<body>", '<body class="product-page">', 1)
    page = page.replace('<button onclick="closeLightbox()" style=',
                        '<button type="button" aria-label="Close enlarged photo" onclick="closeLightbox()" style=')
    page = LOCAL_LINK.sub(r"\1../\2\3", page)
    return page.replace("<!DOCTYPE html>", f"<!DOCTYPE html>\n{GENERATED}", 1)


def build():
    homepage = (ROOT / "index.html").read_text(encoding="utf-8")
    categories = re.search(r'<section class="categories reveal">(.*?)</section>', homepage, re.S)
    category_links = re.findall(
        r'<h2 class="category-title">(.*?)</h2><a href="([^"]+\.html)"',
        categories[1],
    )
    outputs = {}
    search = []

    for category_title, category_file in category_links:
        path = ROOT / category_file
        source = path.read_text(encoding="utf-8")
        grid = GRID.search(source)
        category = plain_text(category_title)
        cards = grid[2]
        updated = []
        end = 0
        for start, stop, attrs in CardParser(cards).cards:
            card = cards[start:stop]
            updated.append(cards[end:start])
            end = stop
            if "data-product-placeholder" in attrs:
                updated.append(card)
                continue
            heading = HEADING.search(card)
            name = plain_text(heading[1])
            slug = attrs.get("data-product-slug", "")
            if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
                raise ValueError(f'{category_file}: give {name!r} a unique data-product-slug')
            destination = PRODUCTS / f"{slug}.html"
            if destination in outputs:
                raise ValueError(f"Duplicate product slug: {slug}")
            href = destination.relative_to(ROOT).as_posix()
            price = plain_text(PRICE.search(card)[1])
            in_stock = bool(re.fullmatch(r"(?:\$\s*\d+(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?\s*\$)", price))
            outputs[destination] = product_page(source, path, category, name, card, in_stock)
            search.append({"name": name, "category": category, "page": href})
            image_link = f'<a class="product-image-link" href="{href}" tabindex="-1" aria-hidden="true"></a>'
            card = IMAGE_LINK.sub("", card)
            card = GALLERY.sub(
                lambda gallery: gallery[1] + image_link + gallery[2] + gallery[3],
                card,
                count=1,
            )
            updated.append(HEADING.sub(
                lambda _: f'<h3><a class="product-title-link" href="{href}">{escape(name)}</a></h3>',
                card,
                count=1,
            ))

        updated.append(cards[end:])
        outputs[path] = source[:grid.start(2)] + "".join(updated) + source[grid.end(2):]

    entries = ",\n".join(f"  {json.dumps(item, ensure_ascii=False)}" for item in search)
    outputs[ROOT / "products.js"] = (
        "// Generated by tools/build_product_pages.py from the linked category pages.\n"
        f"const allProducts = [\n{entries}\n];\n"
    )
    return outputs, len(search)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that generated files are current.")
    args = parser.parse_args()
    outputs, count = build()
    stale = False
    for path, content in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing == content:
            continue
        if args.check:
            print(f"Out of date: {path.relative_to(ROOT)}")
            stale = True
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content, encoding="utf-8")
    orphans = [path for path in PRODUCTS.glob("*.html")
               if path not in outputs and GENERATED in path.read_text(encoding="utf-8")]
    for path in orphans:
        print(f"Retired product URL needs review: {path.relative_to(ROOT)}")
    if stale or orphans:
        raise SystemExit(1)
    print(f"{'Verified' if args.check else 'Generated'} {count} product pages and search entries.")


if __name__ == "__main__":
    main()
